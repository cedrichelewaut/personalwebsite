const LANGS = ["en", "fr", "nl"];
const LANG_NAMES = { en: "English", fr: "Français", nl: "Nederlands" };

function detectLang() {
  try {
    const saved = localStorage.getItem("fa_lang");
    if (LANGS.includes(saved)) return saved;
  } catch {}
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : "en";
}

let LANG = detectLang();

function t(key, vars = {}) {
  const text = (UI_TEXT[LANG] && UI_TEXT[LANG][key]) ?? UI_TEXT.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Static text in the page: data-i18n="key" sets the text, data-i18n-attr="attr:key" sets an attribute.
function applyStatic() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((n) => (n.textContent = t(n.dataset.i18n)));
  document.querySelectorAll("[data-i18n-attr]").forEach((n) => {
    const [attr, key] = n.dataset.i18nAttr.split(":");
    n.setAttribute(attr, t(key));
  });
  const titleKey = document.body.dataset.titleKey;
  if (titleKey) document.title = t(titleKey);
  const desc = document.querySelector('meta[name="description"]');
  if (desc && document.body.dataset.descKey) desc.setAttribute("content", t(document.body.dataset.descKey));
  const sel = document.getElementById("lang");
  if (sel) {
    sel.value = LANG;
    sel.setAttribute("aria-label", t("lang_label"));
  }
}

function setLang(l) {
  if (!LANGS.includes(l) || l === LANG) return;
  LANG = l;
  try {
    localStorage.setItem("fa_lang", l);
  } catch {}
  applyStatic();
  window.dispatchEvent(new Event("langchange"));
}

document.addEventListener("DOMContentLoaded", () => {
  const sel = document.getElementById("lang");
  if (sel) {
    LANGS.forEach((l) => sel.append(Object.assign(document.createElement("option"), { value: l, textContent: LANG_NAMES[l] })));
    sel.addEventListener("change", () => setLang(sel.value));
  }
  applyStatic();
});
